// STYLE RULES (breaking them makes the UI read like two different products):
//
//   1. Sentence case. Only the first word is capitalised: "Add rule",
//      "System status". Title Case ("Add Rule") is the older convention and
//      now reads as dated or machine-generated; Chrome's own UI uses
//      sentence case throughout.
//   2. Proper nouns are the exception: GhostTrace, Chrome, Google, Topics
//      API, Protected Audience, Attribution Reporting, IndexedDB, Service
//      Worker, Public Suffix List, CHIPS, HSTS, QUIC, JSON, Manifest V3.
//   3. One term, one word: "third-party" (not "3rd-party"), "cleanup" (not
//      "cleaning" as a noun), "whitelist", "session list".
//   4. No "Do you want to continue?" in dialogs. The confirm button already
//      says what happens; asking twice is noise.
//   5. No filler adverbs: "successfully", "Successfully imported". If it
//      happened, it happened.
//   6. No trailing colons on labels: "Language" — not "Language:".
//   7. Straight quotes and apostrophes only, never curly.

